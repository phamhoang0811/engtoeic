    private function relatedMeanings(string $relatedWords, array $catalogMeanings): ?string
    {
        if ($relatedWords === '') {
            return null;
        }

        $meanings = array_map(
            fn (string $word) => str_replace(',', ';', $catalogMeanings[mb_strtolower(trim($word))]
                ?? self::RELATED_MEANINGS[mb_strtolower(trim($word))]
                ?? ''),
            explode(',', $relatedWords),
        );

        return implode(', ', $meanings);
    }
